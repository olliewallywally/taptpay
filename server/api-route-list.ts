/**
 * R1-T10a — the list of API routes a browser calls, as the client is given it.
 *
 * The client names a route by its registration ("PUT /api/merchants/:id/theme") and a small builder
 * fills its path (shared/api-path.ts). The names it may use are written to shared/api-routes.ts, as
 * TYPES ONLY, from the server's own registrations and their review: so a page and the server cannot
 * disagree about a path, or about the shape of an id, without the type check or
 * server/__tests__/api-route-contract.test.ts failing.
 *
 * Listed: every route under /api whose review serves a business login, the platform admin, anyone, or
 * the holder of a link. Left out: what only the payment or messaging provider, the scheduler or an
 * ecommerce API key calls (none of them a browser), and the provider notifications registered for
 * every method.
 *
 * scripts/generate-route-policy.ts writes the file in the same run as the policy.
 */
import { expandFacts, type RecordedRouteFacts } from "./route-facts";
import { ROUTE_POLICY } from "./route-policy";
import { ROUTE_REVIEW, type ReviewedPrincipal, type RouteReview } from "./route-review";

export const API_ROUTES_FILE = "shared/api-routes.ts";

/** Who a browser can be: a signed-in business login, the platform admin, anyone, a link's holder. */
const BROWSER_PRINCIPALS: ReadonlySet<ReviewedPrincipal> = new Set(["merchant", "platform-admin", "public", "public-bearer"]);
/** The one server parser that makes a path parameter a whole number (server/http-params.ts). */
const INTEGER_PARSER = "strictPositiveIntegerParam";
const PATH_PARAMETER = /:([A-Za-z][A-Za-z0-9]*)/g;

export interface ListedApiRoute {
  /** The registration: "<METHOD> <path>". */
  key: string;
  method: string;
  path: string;
  /** Each parameter of the path, in order, with the type the server's parser gives it. */
  params: Array<{ name: string; type: "number" | "string" }>;
}

/**
 * The routes listed, in a fixed order. The generator passes the registrations it has just read
 * (route-policy.ts is rewritten in the same run); everything else reads the checked-in policy.
 */
export function browserApiRoutes(
  registrations: ReadonlyArray<{ method: string; path: string; facts: RecordedRouteFacts }> = Object.values(ROUTE_POLICY),
  review: Record<string, RouteReview> = ROUTE_REVIEW,
): ListedApiRoute[] {
  return registrations
    .filter(({ method, path }) => path.startsWith("/api/") && method !== "ALL"
      && (review[`${method} ${path}`]?.branches ?? []).some((branch) => BROWSER_PRINCIPALS.has(branch.principal)))
    .map(({ method, path, facts }): ListedApiRoute => {
      const parsers = new Map(expandFacts(facts).params.map((entry) => {
        const [name, how] = entry.split(": ");
        return [name, how.split(" | ")] as const;
      }));
      return {
        key: `${method} ${path}`,
        method,
        path,
        params: [...path.matchAll(PATH_PARAMETER)].map((match) => ({
          name: match[1],
          type: (parsers.get(match[1]) ?? []).includes(INTEGER_PARSER) ? "number" : "string",
        })),
      };
    })
    .sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0));
}

/** shared/api-routes.ts, whole: the same text for the same registrations, on any machine and any day. */
export function renderApiRoutes(routes: ListedApiRoute[] = browserApiRoutes()): string {
  const entry = (route: ListedApiRoute) => {
    const params = route.params.length
      ? `{ ${route.params.map((param) => `${param.name}: ${param.type}`).join("; ")} }`
      : "Record<never, never>";
    return `  "${route.key}": ${params};`;
  };
  return `/**
 * R1-T10a — every API route a browser calls, named by its registration, with the type of each
 * parameter of its path. GENERATED by scripts/generate-route-policy.ts from the server's own
 * registrations (server/api-route-list.ts says which are listed). Do not edit: change the route, then
 * run the generator. server/__tests__/api-route-contract.test.ts fails when this file and the
 * server differ.
 *
 * Types only: nothing here reaches a bundle. A parameter the server reads as a strict positive
 * integer is a number; any other is text. Build an address with apiPath (shared/api-path.ts).
 */
export interface ApiRouteParams {
${routes.map(entry).join("\n")}
}

/** The name of a route: "<METHOD> <path>", exactly as server/routes.ts registers it. */
export type ApiRouteKey = keyof ApiRouteParams;
`;
}
