import { chromium } from 'playwright';
import { newMobilePage, CHROMIUM_PATH, BASE_URL } from './mobile-fixtures.mjs';
import { newRetailPage } from './desktop-shots/retail-fixtures.mjs';
const browser = await chromium.launch({ executablePath: CHROMIUM_PATH, headless: true });
try {
for (const [width, height] of [[390,844],[320,568],[430,932]]) {
 const { page, context } = await newMobilePage(browser, 'trades', {width,height});
 await page.goto(`${BASE_URL}/trades/terminal`);
 await page.locator('[data-demo-id="trades-mode-quote"]').click();
 await page.getByRole('button',{name:'Build quote',exact:true}).waitFor();
 await page.waitForTimeout(750);
 await page.screenshot({path:`/tmp/quote-${width}-start.png`});
 const size = await page.locator('.mq-hero').boundingBox();
 if (Math.abs(size.height / height - .35) > .01) throw Error(`Wrong split ${width}: ${size.height}`);
 await page.getByRole('button',{name:'Build quote',exact:true}).click();
 await page.waitForTimeout(750);
 await page.screenshot({path:`/tmp/quote-${width}-client.png`});
 const nameBefore = await page.getByLabel('name',{exact:true}).boundingBox();
 await page.getByRole('button',{name:'Choose client',exact:true}).click();
 await page.waitForTimeout(520);
 const nameAfter = await page.getByLabel('name',{exact:true}).boundingBox();
 if(nameAfter.y < nameBefore.y + 80) throw Error('Directory did not push the fields down');
 await page.screenshot({path:`/tmp/quote-${width}-directory.png`});
 await page.getByRole('button',{name:'Choose client',exact:true}).click();
 await page.waitForTimeout(520);
 await page.getByLabel('name',{exact:true}).fill('Sam');
 const fieldStyle = await page.getByLabel('name',{exact:true}).evaluate(el => ({bg:getComputedStyle(el).backgroundColor,fg:getComputedStyle(el).color}));
 if(!fieldStyle.bg.startsWith('rgba(') || fieldStyle.fg !== 'rgb(185, 220, 255)') throw Error(`Unreadable field ${JSON.stringify(fieldStyle)}`);
 await page.getByRole('button',{name:'skip',exact:true}).click();
 await page.getByLabel('Item 1 description').fill('Repair tap');
 await page.getByLabel('Item 1 unit price').fill('100');
 await page.getByRole('button',{name:'Next',exact:true}).click();
 await page.getByRole('button',{name:'Back',exact:true}).click();
 await page.getByLabel('Item 1 description').waitFor();
 if(await page.getByLabel('Item 1 description').inputValue() !== 'Repair tap') throw Error('Back lost the draft');
 await page.getByRole('button',{name:'Next',exact:true}).click();
 await page.getByRole('button',{name:'require deposit',exact:true}).click();
 await page.getByRole('button',{name:'custom',exact:true}).click();
 await page.waitForTimeout(750);
 await page.getByLabel('Quote notes').fill('Please confirm the work before we start.');
 const scrollbar = await page.locator('.mq-scroll').evaluate(el => getComputedStyle(el).scrollbarWidth);
 if(scrollbar !== 'none') throw Error(`Visible scrollbar: ${scrollbar}`);
 await page.screenshot({path:`/tmp/quote-${width}-deposit.png`});
 await page.route('**/api/trades/quotes', async route => {
  if(route.request().method() !== 'POST') return route.fulfill({json:[]});
  const body=route.request().postDataJSON();
  if(!body.skipClient || body.clientProfileId || body.recipient) throw Error('Invalid skip payload');
  await route.fulfill({status:201,json:{id:'q1',token:'test-quote',delivered:false}});
 });
 await page.getByRole('button',{name:'create quote',exact:true}).click();
 await page.getByRole('button',{name:'share',exact:true}).waitFor();
 await page.waitForTimeout(750);
 await page.screenshot({path:`/tmp/quote-${width}-success.png`});
 console.log(`${width}x${height}: 35/65 split, complete skip flow, success passed`);
 await context.close();
}
const reduced = await newMobilePage(browser, 'trades', {width:390,height:844});
await reduced.page.emulateMedia({reducedMotion:'reduce'});
await reduced.page.goto(`${BASE_URL}/trades/quote`);
await reduced.page.getByRole('button',{name:'Build quote',exact:true}).click();
await reduced.page.getByRole('button',{name:'Choose client',exact:true}).waitFor();
const animations = await reduced.page.locator('.mq-page').evaluate(el => el.getAnimations().length);
if(animations) throw Error('Reduced-motion preference ignored');
await reduced.page.getByRole('button',{name:'Back',exact:true}).click();
await reduced.page.getByRole('button',{name:'Build quote',exact:true}).waitFor();
console.log('Standalone mobile route and reduced-motion back/next passed');
await reduced.context.close();
const {page,context}=await newRetailPage(browser,'quote-desktop',{viewport:{width:1440,height:900}});
await page.goto(`${BASE_URL}/trades/quote`);
await page.locator('[data-tutorial-id="trades-quote-create"]').waitFor();
if(await page.locator('.mq-screen').count()) throw Error('Mobile wizard leaked onto desktop');
console.log('Desktop standalone quote retains original form');
await context.close();
} finally {await browser.close();}
